from typing import Protocol
from uuid import UUID

from src.application.dto.responder_evaluacion import EvaluacionDetalle, RespuestaEvaluacion, ResultadoEvaluacion


class ResponderEvaluacion(Protocol):
    def consultar(self, usuario_id: UUID, asignacion_id: UUID) -> EvaluacionDetalle: ...
    def iniciar(self, usuario_id: UUID, asignacion_id: UUID) -> EvaluacionDetalle: ...
    def guardar(self, usuario_id: UUID, asignacion_id: UUID, respuestas: tuple[RespuestaEvaluacion, ...]) -> EvaluacionDetalle: ...
    def finalizar(self, usuario_id: UUID, asignacion_id: UUID, respuestas: tuple[RespuestaEvaluacion, ...]) -> ResultadoEvaluacion: ...
    def resultado_inicial(self, usuario_id: UUID) -> ResultadoEvaluacion: ...
