from typing import Protocol
from uuid import UUID

from src.application.dto.resultados import MisTrabajadores, ResultadoResumen


class ConsultaResultados(Protocol):
    def propios(self, usuario_id: UUID) -> tuple[ResultadoResumen, ...]: ...
    def detalle_propio(self, usuario_id: UUID, resultado_id: UUID) -> ResultadoResumen: ...
    def trabajadores(self, psicologo_id: UUID) -> MisTrabajadores: ...
    def de_trabajador(self, psicologo_id: UUID, trabajador_id: UUID) -> tuple[ResultadoResumen, ...]: ...
    def detalle_profesional(self, psicologo_id: UUID, resultado_id: UUID) -> ResultadoResumen: ...
