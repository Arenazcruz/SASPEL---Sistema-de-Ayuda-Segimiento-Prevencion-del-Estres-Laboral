from contextlib import AbstractContextManager
from typing import Protocol
from uuid import UUID

from src.application.dto.responder_evaluacion import EvaluacionDetalle, RespuestaEvaluacion


class ResponderEvaluacionRepository(Protocol):
    def atomic(self, usuario_id: UUID, asignacion_id: UUID) -> AbstractContextManager: ...
    def consultar(self, usuario_id: UUID, asignacion_id: UUID) -> EvaluacionDetalle: ...
    def iniciar(self, usuario_id: UUID, asignacion_id: UUID) -> None: ...
    def guardar(self, usuario_id: UUID, aplicacion_id: UUID, respuestas: tuple[RespuestaEvaluacion, ...]) -> None: ...
    def finalizar(self, usuario_id: UUID, asignacion_id: UUID, aplicacion_id: UUID) -> None: ...
