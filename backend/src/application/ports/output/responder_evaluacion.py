from contextlib import AbstractContextManager
from typing import Protocol
from uuid import UUID

from decimal import Decimal
from src.application.dto.responder_evaluacion import EvaluacionDetalle, RespuestaEvaluacion, ResultadoEvaluacion
from src.domain.services.resultado_evaluacion import ItemPuntaje, RangoPuntaje


class ResponderEvaluacionRepository(Protocol):
    def atomic(self, usuario_id: UUID, asignacion_id: UUID) -> AbstractContextManager: ...
    def consultar(self, usuario_id: UUID, asignacion_id: UUID) -> EvaluacionDetalle: ...
    def iniciar(self, usuario_id: UUID, asignacion_id: UUID) -> None: ...
    def guardar(self, usuario_id: UUID, aplicacion_id: UUID, respuestas: tuple[RespuestaEvaluacion, ...]) -> None: ...
    def finalizar(self, usuario_id: UUID, asignacion_id: UUID, aplicacion_id: UUID) -> None: ...
    def rol(self, usuario_id: UUID) -> str: ...
    def datos_calculo(self, aplicacion_id: UUID) -> tuple[tuple[ItemPuntaje, ...], tuple[RangoPuntaje, ...]]: ...
    def crear_resultado(self, usuario_id: UUID, aplicacion_id: UUID, puntaje: Decimal, rango_id: UUID | None) -> None: ...
    def completar_onboarding(self, usuario_id: UUID) -> None: ...
    def resultado(self, usuario_id: UUID, asignacion_id: UUID) -> ResultadoEvaluacion | None: ...
    def resultado_inicial(self, usuario_id: UUID) -> ResultadoEvaluacion: ...
