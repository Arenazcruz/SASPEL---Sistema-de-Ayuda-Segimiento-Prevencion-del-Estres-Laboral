    def cambiar_estado(self, cita_id, estado, motivo, actor_id): ...
    def disponibilidad(self, psicologo_id): ...
    def guardar_disponibilidad(self, psicologo_id, datos): ...
    def desactivar_disponibilidad(self, psicologo_id, bloque_id): ...

