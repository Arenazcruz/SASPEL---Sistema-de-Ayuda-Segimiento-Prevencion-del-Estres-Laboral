    def atomic(self): ...
    def rol_activo(self, usuario_id): ...
    def tiene_asignacion_activa(self, psicologo_id, trabajador_id): ...
    def listar(self, usuario_id, rol): ...
    def contexto(self, trabajador_id): ...
    def solicitar(self, trabajador_id, datos): ...
    def obtener(self, cita_id): ...
