from contextlib import AbstractContextManager
from typing import Protocol
from uuid import UUID

from src.application.dto.resultados import MisTrabajadores, ResultadoResumen


class ResultadosRepository(Protocol):
    def atomic(self) -> AbstractContextManager: ...
    def rol_activo(self, usuario_id: UUID) -> str | None: ...
    def tiene_asignacion_activa(self, psicologo_id: UUID, trabajador_id: UUID) -> bool: ...
    def trabajadores(self, psicologo_id: UUID) -> MisTrabajadores: ...
    def listar_resultados(self, trabajador_id: UUID) -> tuple[ResultadoResumen, ...]: ...
    def resultado(self, resultado_id: UUID) -> tuple[UUID, ResultadoResumen] | None: ...
