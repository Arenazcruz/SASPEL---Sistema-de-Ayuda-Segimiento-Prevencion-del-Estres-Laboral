"""Contrato de datos administrativos. Django lo implementa en repositories/administration.py;
al cambiar persistencia conservar DTO, errores y garantías de atomic().
"""

from contextlib import AbstractContextManager
from typing import Protocol
from src.application.dto.superadmin import (
    CreateUserCommand, DashboardSummary, InstitutionDTO, UserDTO, UserFilters, UserPage,
)


class AdministrationRepository(Protocol):
    """Operaciones que Application necesita sin importar modelos Django."""
    # Transacción con rollback y bloqueo para proteger al último Superadmin.
    def atomic(self) -> AbstractContextManager: ...
    # UserFilters -> UserPage filtrada y paginada; no escribe.
    def list_users(self, filters: UserFilters) -> UserPage: ...
    # ID -> UserDTO o PersonNotFound; no escribe.
    def get_user(self, user_id: int) -> UserDTO: ...
    # Crea cuenta/perfil/grupo y devuelve UserDTO; exige atomic del caso.
    def create_user(self, command: CreateUserCommand) -> UserDTO: ...
    # ID/cambios personales -> UserDTO actualizado; exige atomic del caso.
    def update_user(self, user_id: int, changes: dict) -> UserDTO: ...
    # Guarda acceso activo/inactivo; devuelve UserDTO. El caso protege al actor.
    def set_active(self, user_id: int, active: bool) -> UserDTO: ...
    # Reemplaza grupo y sincroniza flags/perfil; devuelve UserDTO.
    def set_role(self, user_id: int, role: str) -> UserDTO: ...
    # Cuenta activos del grupo SUPERADMIN para proteger el último acceso.
    def active_superadmins(self) -> int: ...
    # ID/clave -> guarda hash y devuelve None; valida antes de persistir.
    def reset_password(self, user_id: int, password: str) -> None: ...
    # Devuelve DashboardSummary de cuentas actuales; no escribe.
    def summary(self) -> DashboardSummary: ...
    # kind areas/cargos, active opcional -> lista de DTO; None incluye todos.
    def list_institution(self, kind: str, active: bool | None) -> list[InstitutionDTO]: ...
    # kind/ID -> InstitutionDTO o PersonNotFound; no escribe.
    def get_institution(self, kind: str, item_id: int) -> InstitutionDTO: ...
    # kind/ID/cambios -> DTO guardado; ID None crea. Exige atomic del caso.
    def save_institution(self, kind: str, item_id: int | None, changes: dict) -> InstitutionDTO: ...
