from contextlib import AbstractContextManager
from typing import Literal, Protocol
from uuid import UUID

from src.application.dto.instrument_content import ContentFilters, ContentKind, ContentPage, ContentRecord


class ContentRepository(Protocol):
    def atomic(self, kind: ContentKind, parent_id: UUID | None) -> AbstractContextManager: ...
    def list(self, kind: ContentKind, parent_id: UUID | None, filters: ContentFilters) -> ContentPage: ...
    def get(self, kind: ContentKind, parent_id: UUID | None, item_id: UUID, *, lock: bool = False) -> ContentRecord: ...
    def create(self, kind: ContentKind, parent_id: UUID | None, data: dict) -> ContentRecord: ...
    def update(self, kind: ContentKind, parent_id: UUID | None, item_id: UUID, data: dict) -> ContentRecord: ...
    def move(self, kind: ContentKind, parent_id: UUID, item_id: UUID, direction: Literal['up', 'down']) -> ContentRecord: ...
