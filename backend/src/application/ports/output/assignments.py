"""Persistencia requerida por T23. atomic debe coordinarse con cambios de rol y habilitación."""

from contextlib import AbstractContextManager
from typing import Protocol
from src.application.dto.assignments import (
    AssignmentDTO, AssignmentFilters, AssignmentPage, AssignmentPerson,
    PsychologistLoad, WorkerPage,
)


class AssignmentRepository(Protocol):
    def atomic(self) -> AbstractContextManager: ...
    def list_assignments(self, filters: AssignmentFilters) -> AssignmentPage: ...
    def unassigned_workers(self, search: str, page: int) -> WorkerPage: ...
    def psychologist_loads(self) -> list[PsychologistLoad]: ...
    def get_person(self, user_id: int) -> AssignmentPerson: ...
    # Las siguientes lecturas/escrituras se realizan dentro de atomic.
    def get_assignment(self, assignment_id: int) -> AssignmentDTO: ...
    def has_active_assignment(self, worker_id: int) -> bool: ...
    def create_assignment(self, worker_id: int, psychologist_id: int) -> AssignmentDTO: ...
    def close_assignment(self, assignment_id: int, state: str, reason: str) -> AssignmentDTO: ...
