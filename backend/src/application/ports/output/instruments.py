"""Persistencia del catálogo existente; no ofrece eliminación."""

from typing import Protocol
from uuid import UUID
from src.application.dto.instruments import InstrumentDTO, InstrumentData, InstrumentFilters, InstrumentPage


class InstrumentRepository(Protocol):
    def list(self, filters: InstrumentFilters) -> InstrumentPage: ...
    def get(self, instrument_id: UUID) -> InstrumentDTO: ...
    def create(self, data: InstrumentData) -> InstrumentDTO: ...
    def update(self, instrument_id: UUID, changes: dict) -> InstrumentDTO: ...
    def set_active(self, instrument_id: UUID, active: bool) -> InstrumentDTO: ...
