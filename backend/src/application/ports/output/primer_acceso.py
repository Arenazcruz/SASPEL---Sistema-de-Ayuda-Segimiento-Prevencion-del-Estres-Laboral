from contextlib import AbstractContextManager
from datetime import datetime
from typing import Protocol
from uuid import UUID

from src.application.dto.primer_acceso import CuentaPrimerAcceso, PoliticaDTO


class PrimerAccesoRepository(Protocol):
    def atomic(self, usuario_id: UUID) -> AbstractContextManager: ...
    def cuenta(self, usuario_id: UUID) -> CuentaPrimerAcceso: ...
    def ahora(self) -> datetime: ...
    def politicas(self) -> list[PoliticaDTO]: ...
    def aceptadas(self, usuario_id: UUID) -> set[UUID]: ...
    def cambiar_password(self, usuario_id: UUID, password: str) -> None: ...
    def aceptar(self, usuario_id: UUID, politicas: set[UUID]) -> None: ...
